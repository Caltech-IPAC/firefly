export const getColorModel= (colorTableId,nanPixelColor) => {

    if (colorTableId===NO_COLOR_TABLE) return undefined;
    const basePaletteData= getColorModelBase(colorTableId);
    if (!nanPixelColor || !basePaletteData) return basePaletteData;

    const paletteData = Float32Array.of(...basePaletteData);
    const nanPix= nanPixelColor.length >2 ? nanPixelColor : [0,0,0];
    paletteData[3*255]     = nanPix[0]/255;
    paletteData[3*255 + 1] = nanPix[1]/255;
    paletteData[3*255 + 2] = nanPix[2]/255;
	return paletteData;
};



export const getColorModelBase= memorizeLastCall((colorTableId) => {
    let old_dn, old_red, old_green, old_blue;
    let offset;
    let k;

    //palette: 3 bytes per color * 256 colors = 768 bytes in length
    const paletteData = new Float32Array(768);
    // const ct= getColorTableMap()[colorTableId+''];
    const ct = getRawColorTableEntry(colorTableId);

    if (colorTableId === 'file') console.log('file color tables not yet supported');

    if (!ct) {
        console.log('ColorTable ERROR: no color table with the ID = ' + colorTableId);
        return [];
    }

    k = 0;
    let dn = ct[k];
    let red = ct[k + 1];
    let green = ct[k + 2];
    let blue = ct[k + 3];
    k += 4;

    while (true) {
        old_dn = dn;
        old_red = red;
        old_green = green;
        old_blue = blue;

        if (k >= ct.length) break;
        dn = ct[k];
        red = ct[k + 1];
        green = ct[k + 2];
        blue = ct[k + 3];
        k += 4;

        const inc = (dn > old_dn) ? 1 : -1;

        for (let kk = old_dn; kk !== dn; kk += inc) {
            if (kk >= 0 && kk <= 255) {
                offset = (kk - old_dn) / (dn - old_dn);
                paletteData[3 * kk] = (old_red + Math.trunc(offset * (red - old_red))) / 255;
                paletteData[3 * kk + 1] = (old_green + Math.trunc(offset * (green - old_green))) / 255;
                paletteData[3 * kk + 2] = (old_blue + Math.trunc(offset * (blue - old_blue))) / 255;
            }
        }
    }

    if (old_dn >= 0 && old_dn <= 255) {
        paletteData[3 * old_dn] = old_red / 255;
        paletteData[3 * old_dn + 1] = old_green / 255;
        paletteData[3 * old_dn + 2] = old_blue / 255;
    }

    return paletteData;
});


const makeRGBKey= (r,g,b) =>`${r}-${g}-${b}`;

/**
 *
 * @param {string|number} fromId
 * @param {string|number} toId
 * @return {function(number=, number=, number=): {r: number, b: number, g: number}}
 */
export function makeColorModelConverter(fromId, toId) {
    const fromCM= getColorModel(fromId);
	const toCM= getColorModel(toId);
	const convertObj= {};
	let key;
	for(let i=0, j=0; i<fromCM.length-3; i+=3, j++) {
		key= makeRGBKey(fromCM[i],fromCM[i+1],fromCM[i+2]);
		convertObj[key]= j;
	}
	return (r,g,b) => {
		const idx= convertObj[makeRGBKey(r,g,b)] ?? 0;
		const toIdx= idx*3;
		return {r: toCM[toIdx], g:toCM[toIdx+1], b:toCM[toIdx+2]};
	};
}

